# =============================================================================
# Embed デフォルトカラー
# =============================================================================

# Bot が送信する Embed のデフォルト色
DEFAULT_EMBED_COLOR = 0x85E7AD

# =============================================================================
# アプリケーション基本設定
# =============================================================================

# アプリケーション名
# pyproject.toml の name と一致させる
APP_NAME = "tmp-vc-bot"

# データベース名
# PostgreSQL はハイフンを含む識別子を許可しないため、アンダースコアに変換
